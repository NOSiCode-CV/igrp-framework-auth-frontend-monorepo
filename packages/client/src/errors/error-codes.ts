/**
 * RFC-7807 problem-details response body as returned by the API's
 * `GlobalExceptionHandler` on every error. The standard members
 * (`type`, `title`, `status`, `detail`, `instance`) follow RFC 7807;
 * `code` and `details` are API-specific extensions.
 */
export interface ProblemDetail {
    /** RFC-7807 problem type URI. May be absent. */
    type?: string;
    /** Human-readable summary — also exposed as `ApiClientError.title`. */
    title?: string;
    /** HTTP status code on the wire. Mirrors the response status. */
    status?: number;
    /** Detailed explanation when supplied by the server. */
    detail?: string;
    /** Problem instance URI when supplied by the server. */
    instance?: string;
    /** IGRP error code string — match against `IgrpErrorCode.*`. */
    code?: IgrpErrorCode | string;
    /** Opaque per-endpoint extra context. Shape is endpoint-specific. */
    details?: unknown;
    /** Any further RFC-7807 extension properties returned by the server. */
    [key: string]: unknown;
}
